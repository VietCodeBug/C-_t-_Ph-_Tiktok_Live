from playwright.sync_api import sync_playwright
from pathlib import Path
import json, os

out=Path(__file__).resolve().parents[1]/'artifacts'/'gameplay-v4'
out.mkdir(parents=True,exist_ok=True)
report={'checks':[],'errors':[],'failed_requests':[]}
def check(name,value,detail=None):
    report['checks'].append({'name':name,'passed':bool(value),'detail':detail})
    assert value,(name,detail)

with sync_playwright() as p:
    options={'headless':True,'args':['--enable-unsafe-swiftshader']}
    if os.environ.get('CHROMIUM_PATH'):options['executable_path']=os.environ['CHROMIUM_PATH']
    browser=p.chromium.launch(**options)
    page=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
    page.on('pageerror',lambda error:report['errors'].append(str(error)))
    page.on('console',lambda msg:report['errors'].append(msg.text) if msg.type=='error' else None)
    page.on('requestfailed',lambda request:report['failed_requests'].append(request.url))
    page.goto(os.environ.get('WEB_PREVIEW_URL','http://127.0.0.1:4174/?seed=42&mode=classic'),wait_until='networkidle')
    page.wait_for_function('window.__TYPHI__?.ready || document.querySelector(".retry-button")',timeout=60000)
    assert page.evaluate('!!window.__TYPHI__?.ready'),report['errors']
    page.evaluate("window.__TYPHI__.pause(true);window.__TYPHI__.mode('overview')")
    page.wait_for_timeout(1800)
    initial=page.evaluate('window.__TYPHI__.snapshot()')
    layout=page.evaluate('window.__TYPHI__.layout()')
    check('winding map has 138 nodes and six visible fork definitions',len(layout['nodes'])==138 and sum(n['fork'] for n in layout['nodes'])==6)
    check('wallets start at 1000 for ten seats',all(player['money']==1000 for player in initial['players']))
    check('map has no invalid geometry',page.evaluate('window.__TYPHI__.geometryAudit()')==[])
    page.screenshot(path=str(out/'01-overview-mobile.png'),full_page=True)
    page.evaluate('window.__TYPHI__.previewFork()')
    page.wait_for_function("window.__TYPHI__.snapshot().phase==='roll'")
    page.wait_for_timeout(250)
    page.evaluate('window.__TYPHI__.pause(true)')
    style=page.locator('.dice-overlay').evaluate("el=>({background:getComputedStyle(el).backgroundColor,border:getComputedStyle(el).borderTopWidth,shadow:getComputedStyle(el).boxShadow,backdrop:getComputedStyle(el).backdropFilter})")
    check('die floats with no white panel border shadow or blur',style=={'background':'rgba(0, 0, 0, 0)','border':'0px','shadow':'none','backdrop':'none'},style)
    page.screenshot(path=str(out/'02-dice-no-panel.png'),full_page=True)
    page.evaluate('window.__TYPHI__.pause(false)')
    page.wait_for_function("window.__TYPHI__.snapshot().phase==='fork-choice'",timeout=30000)
    page.evaluate('window.__TYPHI__.pause(true)')
    branch=page.evaluate('window.__TYPHI__.snapshot()')
    box=page.locator('#branch-bar').bounding_box();portrait=page.locator('#portrait').bounding_box()
    check('left right selection bar appears near the top of portrait',box['y']-portrait['y']<portrait['height']*.2 and page.locator('[data-direction]').count()==2)
    check('branch choices explain routes and stop before any step',all(option['preview'] for option in branch['branch']['options']) and branch['stepsCompleted']==0)
    remaining=branch['branch']['remainingSeconds']
    page.wait_for_timeout(250)
    check('pause freezes choice timer and disables both buttons',page.evaluate('window.__TYPHI__.snapshot().branch.remainingSeconds')==remaining and page.locator('[data-direction=left]').is_disabled())
    page.screenshot(path=str(out/'03-fork-choice-mobile.png'),full_page=True)
    page.evaluate('window.__TYPHI__.pause(false)')
    page.locator('[data-direction=right]').click()
    chosen=page.evaluate('window.__TYPHI__.snapshot()')
    check('right button commits once and resumes same roll',chosen['branch'] is None and chosen['roll']==branch['roll'] and chosen['remaining']==branch['remaining'] and chosen['lastChoice']['direction']=='right')
    page.wait_for_timeout(450)
    check('normal movement uses relaxed walk artwork',page.evaluate('window.__TYPHI__.snapshot().players[window.__TYPHI__.snapshot().active].clip')=='walk')

    def visit(category):
        page.evaluate('(category)=>window.__TYPHI__.previewEvent(category)',category)
        page.wait_for_function('(category)=>window.__TYPHI__.snapshot().event?.category===category',arg=category)
        page.wait_for_timeout(180)

    visit('gain')
    gain=page.evaluate('window.__TYPHI__.snapshot()')
    check('landing income posts once and updates the visible wallet',gain['event']['result']['delta']>0 and gain['money']==1000+gain['event']['result']['delta'] and page.locator('#turn-money').inner_text()==f"{gain['money']:,}".replace(',','.'))
    check('income has 3D particles and a floating money label',page.locator('.money-pop').is_visible())
    page.evaluate('window.__TYPHI__.pause(true)')
    page.screenshot(path=str(out/'04-income-mobile.png'),full_page=True)
    visit('loss')
    loss=page.evaluate('window.__TYPHI__.snapshot()')
    check('fee changes MONEY and ledger explains before and after',loss['event']['result']['delta']<0 and loss['ledger'][-1]['before']==gain['money'] and loss['ledger'][-1]['after']==loss['money'])
    page.evaluate('window.__TYPHI__.pause(true)')
    page.screenshot(path=str(out/'05-fee-mobile.png'),full_page=True)
    visit('invest')
    invest=page.evaluate('window.__TYPHI__.snapshot()')
    check('investment displays two choices with numeric risk before committing',invest['phase']=='event-choice' and page.locator('[data-event-choice]').count()==2 and '%' in page.locator('#event-options').inner_text())
    page.evaluate('window.__TYPHI__.pause(true)')
    page.screenshot(path=str(out/'06-investment-mobile.png'),full_page=True)
    page.evaluate('window.__TYPHI__.pause(false)')
    choice=invest['event']['choices'][0]['id']
    page.locator('[data-event-choice]').first.click()
    settled=page.evaluate('window.__TYPHI__.snapshot()')
    check('choice records one transaction and repeated submission cannot charge twice',len(settled['ledger'])==len(invest['ledger'])+1 and page.evaluate('(id)=>window.__TYPHI__.chooseEvent(id)',choice) is False)
    visit('rest')
    rest=page.evaluate('window.__TYPHI__.snapshot()')
    check('ordinary tile has no event card no reward effects and unchanged wallet',page.locator('#event-panel').is_hidden() and page.locator('.money-pop').is_hidden() and rest['money']==settled['money'])
    visit('trade')
    check('trade offers salary and an explained simulated sale',page.locator('[data-event-choice]').count()==2 and page.evaluate('window.__TYPHI__.snapshot().phase')=='event-choice')
    page.locator('[data-event-choice]').first.click()
    visit('minigame')
    mini=page.evaluate('window.__TYPHI__.snapshot()')
    correct=next(choice['id'] for choice in mini['event']['choices'] if choice['delta']>0)
    page.locator(f'[data-event-choice="{correct}"]').click()
    check('short local challenge awards displayed MONEY',page.evaluate('window.__TYPHI__.snapshot().event.result.delta')>0)
    page.evaluate('window.__TYPHI__.pause(true)')
    rect=page.locator('#game').bounding_box()
    check('mobile remains 9:16 without horizontal overflow',abs(rect['width']/rect['height']-9/16)<.005 and page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    page.set_viewport_size({'width':1440,'height':1000})
    page.wait_for_timeout(500)
    page.locator('#sound-toggle').click()
    check('sound toggle responds',page.locator('#sound-toggle').get_attribute('aria-pressed')=='false')
    page.locator('#sound-toggle').click()
    page.screenshot(path=str(out/'07-desktop-play.png'),full_page=True)
    page.evaluate("window.__TYPHI__.mode('follow');window.__TYPHI__.previewEvent('loss','LOSS02')")
    page.wait_for_function("window.__TYPHI__.eventCameo().visible && window.__TYPHI__.eventCameo().kind==='dog'")
    page.wait_for_timeout(700)
    page.evaluate('window.__TYPHI__.pause(true)')
    dog=page.evaluate('window.__TYPHI__.eventCameo()')
    dog_state=page.evaluate('window.__TYPHI__.snapshot()')
    check('dog cameo uses supplied sprite without adding a second money transaction',dog['loaded']==2 and dog['frame']>=0 and dog_state['event']['id']=='LOSS02' and dog_state['event']['result']['delta']==-35)
    page.wait_for_timeout(200)
    check('pause freezes cameo animation clock',page.evaluate('window.__TYPHI__.eventCameo().age')==dog['age'])
    page.screenshot(path=str(out/'08-dog-cameo.png'),full_page=True)
    page.evaluate("window.__TYPHI__.previewEvent('loss','LOSS01')")
    page.wait_for_function("window.__TYPHI__.eventCameo().visible && window.__TYPHI__.eventCameo().kind==='police'")
    page.wait_for_timeout(700)
    page.evaluate('window.__TYPHI__.pause(true)')
    police=page.evaluate('window.__TYPHI__.eventCameo()')
    check('police cameo loads and the fee is still applied exactly once',police['frame']>=0 and page.evaluate('window.__TYPHI__.snapshot().event.result.delta')==-60)
    page.screenshot(path=str(out/'09-police-cameo.png'),full_page=True)
    check('no application errors or failed requests',not report['errors'] and not report['failed_requests'],{'errors':report['errors'],'failed_requests':report['failed_requests']})
    browser.close()

report['status']='PASS'
(out/'report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps({'status':'PASS','checks':len(report['checks'])}))
